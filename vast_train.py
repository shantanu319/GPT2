def ssh_prefix(state):
    return ["ssh", f"-p{state['ssh_port']}", *SSH_OPTS, f"root@{state['ssh_host']}"]


def run_remote(state, cmd, check=True):
    """Run a shell command on the instance, streaming output."""
    return subprocess.run(ssh_prefix(state) + [cmd], check=check)


def rsync(state, src, dst, extra_excludes=()):
    ssh_expr = " ".join(["ssh", f"-p{state['ssh_port']}", *SSH_OPTS])
    cmd = ["rsync", "-az", "-e", ssh_expr]
    for pat in list(RSYNC_EXCLUDES) + list(extra_excludes):
        cmd += ["--exclude", pat]
    cmd += [src, dst]
    subprocess.run(cmd, check=True)


def wait_ready(client, instance_id, timeout=12 * 60):
    """Wait for the instance to report running, then for SSH to answer."""
    deadline = time.time() + timeout
    last = None
    while time.time() < deadline:
        info = client.show_instance(id=instance_id) or {}
        status = info.get("actual_status") or info.get("status") or "?"
        if status != last:
            print(f"  instance {instance_id}: {status}", flush=True)
            last = status
        if status == "running":
            state = {
                "id": instance_id,
                "ssh_host": info.get("ssh_host") or info.get("public_ipaddr"),
                "ssh_port": info.get("ssh_port", 22),
                "gpu": info.get("gpu_name"),
                "dph": info.get("dph_total"),
            }
            # sshd can lag the status flip; probe until it answers.
            probe_deadline = time.time() + 4 * 60
            while time.time() < probe_deadline:
                rc = subprocess.run(
                    ssh_prefix(state) + ["true"],
                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                ).returncode
                if rc == 0:
                    return state
                time.sleep(5)
            raise RuntimeError(f"instance {instance_id} is running but SSH never came up")
        time.sleep(10)
    raise RuntimeError(f"instance {instance_id} not running after {timeout // 60} min "
                       f"(last status: {last})")


def pick_offer(client, query, limit=10):
    offers = client.search_offers(query=query, order="dph_total", limit=limit)
    if not offers:
        sys.exit(f"no offers match: {query}")
    return offers


def print_offers(offers):
    print(f"{'id':>10}  {'gpu':<16} {'ram(GB)':>7} {'$/hr':>7} {'down(Mbps)':>10}  {'cuda':<5} {'reliab':>6}  location")
    for o in offers:
        print(f"{o.get('id'):>10}  {str(o.get('gpu_name')):<16} "
              f"{o.get('gpu_ram', 0):>7.0f} {o.get('dph_total', 0):>7.3f} "
              f"{o.get('inet_down', 0):>10.0f}  {o.get('cuda_max_good', 0):<5.1f} "
              f"{o.get('reliability2', 0):>6.3f}  {o.get('geolocation', '?')}")


