def cmd_pipeline(args):
    state = load_state()
    script = PIPELINE_SCRIPT.format(
        root=REMOTE_ROOT,
        data_dir=DATA_DIR,
        dir_name=args.dir_name,
        sft_dir_name=args.sft_dir_name,
        hf_export=(f"export HF_TOKEN={os.environ['HF_TOKEN']}"
                   if os.environ.get("HF_TOKEN") else ""),
        prepare_args=(f"--max-train-docs {args.max_train_docs}" if args.max_train_docs > 0 else ""),
        train_args=(f"-d_model {args.d_model} -n_layers {args.n_layers} -heads {args.heads} "
                    f"-kv_heads {args.kv_heads} -loops {args.loops} "
                    f"-batchsize {args.batchsize} -grad_accum {args.grad_accum} "
                    f"-seqlen {args.seqlen} -epochs {args.epochs} "
                    f"-lr {args.lr} -muon_lr {args.muon_lr} -warmup_steps {args.warmup_steps} "
                    f"-save_every {args.save_every} -val_every {args.val_every} "
                    f"-early_stop {args.early_stop} -early_stop_delta {args.early_stop_delta} "
                    f"-early_stop_cooldown {args.early_stop_cooldown}"),
        sft_args=f"--epochs {args.sft_epochs}",
        dpo_dir_name=args.dpo_dir_name,
        dpo_args=(f"--epochs {args.dpo_epochs} --batchsize {args.dpo_batchsize} "
                  f"--beta {args.dpo_beta} --lr {args.dpo_lr} --muon-lr {args.dpo_muon_lr}"),
    )
    subprocess.run(ssh_prefix(state) + [f"cat > {REMOTE_ROOT}/remote_pipeline.sh"],
                   input=script.encode(), check=True)
    run_remote(state, f"cd {REMOTE_ROOT} && nohup bash remote_pipeline.sh > pipeline.log 2>&1 & "
                      "echo pipeline detached pid $!")
    print("pipeline running server-side (survives laptop sleep). "
          "Watch with ./watch_pipeline.sh or `python vast_train.py status`")


def cmd_status(args):
    client = get_client()
    state = load_state(required=False) or {}
    instance_id = args.id or state.get("id")
    if not instance_id:
        sys.exit("no current instance — pass --id or run create first")
    info = client.show_instance(id=instance_id) or {}
    print(f"instance {instance_id}: {info.get('actual_status', '?')} "
          f"{info.get('gpu_name', '')} ~${info.get('dph_total', 0):.3f}/hr")
    state = state if state.get("id") == instance_id else {
        "id": instance_id,
        "ssh_host": info.get("ssh_host") or info.get("public_ipaddr"),
        "ssh_port": info.get("ssh_port", 22),
    }
    if info.get("actual_status") == "running":
        run_remote(state, f"cd {REMOTE_ROOT} && "
                          "(tail -n 20 pipeline.log 2>/dev/null || true) && echo --- && "
                          "(ls saved/*/ 2>/dev/null || echo 'no checkpoints yet')",
                   check=False)


def cmd_pull(args):
    state = load_state()
    os.makedirs(args.out, exist_ok=True)
    rsync(state, f"root@{state['ssh_host']}:{REMOTE_ROOT}/saved/", f"{args.out}/saved/")
    print(f"pulled saved/ -> {args.out}/saved/")
    ssh_expr = " ".join(["ssh", f"-p{state['ssh_port']}", *SSH_OPTS])
    for f in [f"{DATA_DIR}/tokenizer.json", "pipeline.log", "learning_curves.png"]:
        rc = subprocess.run(
            ["rsync", "-az", "-e", ssh_expr,
             f"root@{state['ssh_host']}:{REMOTE_ROOT}/{f}", f"{args.out}/"],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        ).returncode
        if rc == 0:
            print(f"pulled {f}")
    print(f"artifacts in ./{args.out}/")


def cmd_destroy(args):
    client = get_client()
    state = load_state(required=False) or {}
    instance_id = args.id or state.get("id")
    if not instance_id:
        sys.exit("no current instance — pass --id")
    client.destroy_instance(id=instance_id)
    print(f"destroyed instance {instance_id}")
    if state.get("id") == instance_id:
        clear_state()


def cmd_smoke(args):
    """End-to-end check: cheapest GPU -> CUDA test -> tiny train -> pull -> destroy."""
    client = get_client()
    instance_id = None
    state = None
    t0 = time.time()
    try:
        print("[smoke] searching offers...")
        offer = pick_offer(client, SMOKE_QUERY, limit=5)[0]
        print(f"[smoke] offer {offer['id']}: {offer.get('gpu_name')} "
              f"@ ~${offer.get('dph_total', 0):.3f}/hr")
        resp = client.create_instance(id=offer["id"], image=IMAGE, disk=25,
                                      label="mot-smoke", runtype="ssh")
        instance_id = resp.get("new_contract") or resp.get("id")
        if not instance_id:
            sys.exit(f"[smoke] create failed: {resp}")
        pub = os.path.expanduser(os.environ.get("VAST_SSH_PUBKEY", "~/.ssh/id_ed25519.pub"))
        with open(pub) as f:
            client.attach_ssh(instance_id, f.read().strip())
        state = wait_ready(client, instance_id, timeout=20 * 60)
        save_state(state)

        print("[smoke] GPU + torch check...")
        run_remote(state, "nvidia-smi --query-gpu=name,memory.total --format=csv,noheader && "
                          "python -c \"import torch; a=torch.randn(2048,2048,device='cuda'); "
                          "print('torch', torch.__version__, '| cuda ok:', bool((a@a).sum()))\"")

        print("[smoke] pushing repo...")
        run_remote(state, f"mkdir -p {REMOTE_ROOT}")
        rsync(state, "./", f"root@{state['ssh_host']}:{REMOTE_ROOT}/")

        print("[smoke] tiny train (synthetic shards, ~400 steps on GPU)...")
        run_remote(state, "pip install -q --break-system-packages matplotlib")  # train.py imports it
        gen_bins = (
            f"cd {REMOTE_ROOT} && python -c \""
            "import os, numpy as np; "
            "from tokenizer import BPETokenizer; "
            "d='data_cache/smoke'; os.makedirs(d, exist_ok=True); "
            "t=BPETokenizer(); t.load('data_cache/cosmopedia/tokenizer.json'); "
            "[np.random.randint(0, t.vocab_size, 200_000).astype(np.uint16).tofile(f'{d}/{n}.bin') "
            "for n in ('train','val','test')]; "
            "os.link('data_cache/cosmopedia/tokenizer.json', f'{d}/tokenizer.json'); "
            "print('synthetic shards ready, vocab', t.vocab_size)\""
        )
        run_remote(state, gen_bins)
        run_remote(state, f"cd {REMOTE_ROOT} && MPLBACKEND=Agg python -u train.py "
                          "-data_dir data_cache/smoke -d_model 64 -n_layers 2 -heads 2 "
                          "-batchsize 8 -seqlen 64 -epochs 1 -warmup_steps 5 "
                          "-save_every 0 -val_every 0 -printevery 100 -dir_name smoke")

        print("[smoke] pulling checkpoint back...")
        os.makedirs(f"{args.out}/smoke", exist_ok=True)
        rsync(state, f"root@{state['ssh_host']}:{REMOTE_ROOT}/saved/smoke/", f"{args.out}/smoke/")
        assert os.path.exists(f"{args.out}/smoke/ckpt_final.pt"), "ckpt_final.pt missing after pull"
        print(f"[smoke] PASS in {(time.time() - t0) / 60:.1f} min — "
              f"checkpoint at {args.out}/smoke/ckpt_final.pt")
    finally:
        if instance_id and not args.keep:
            print("[smoke] destroying instance...")
            try:
                client.destroy_instance(id=instance_id)
            except Exception as e:
                print(f"[smoke] WARNING: destroy failed for {instance_id}: {e} — "
                      "destroy it manually at https://cloud.vast.ai/instances/")
            clear_state()
        elif instance_id:
            print(f"[smoke] --keep: instance {instance_id} left running "
                  "(destroy with `python vast_train.py destroy`)")


