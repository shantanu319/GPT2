def get_client():
    from vastai import VastAI
    key = os.environ.get("VAST_API_KEY") or os.environ.get("VAST_AI_API_KEY")
    if not key:
        sys.exit("no VAST_API_KEY or VAST_AI_API_KEY in env or .env.local — "
                 "get one at https://cloud.vast.ai/manage-keys/")
    os.environ["VAST_API_KEY"] = key
    return VastAI(api_key=key)


def hf_env():
    """HF_TOKEN raises HuggingFace streaming rate limits for prepare/sft_prepare."""
    tok = os.environ.get("HF_TOKEN", "")
    return f"HF_TOKEN={tok} " if tok else ""


def load_state(required=True):
    if not os.path.exists(STATE_FILE):
        if required:
            sys.exit(f"no {STATE_FILE} — run `python vast_train.py create` first")
        return None
    with open(STATE_FILE) as f:
        return json.load(f)


def save_state(state):
    with open(STATE_FILE, "w") as f:
        json.dump(state, f, indent=2)


def clear_state():
    if os.path.exists(STATE_FILE):
        os.remove(STATE_FILE)


