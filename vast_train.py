def cmd_offers(args):
    client = get_client()
    print_offers(pick_offer(client, args.query, limit=args.limit))


def cmd_create(args):
    client = get_client()
    offers = pick_offer(client, args.query, limit=10)
    print_offers(offers[:5])
    offer = next((o for o in offers if o.get("id") == args.offer_id), None) \
        if args.offer_id else offers[0]
    print(f"creating instance from offer {offer['id']} "
          f"({offer.get('gpu_name')}, ~${offer.get('dph_total', 0):.3f}/hr)...")
    resp = client.create_instance(
        id=offer["id"], image=args.image, disk=args.disk,
        label=args.label, runtype="ssh",
    )
    instance_id = resp.get("new_contract") or resp.get("id")
    if not instance_id:
        sys.exit(f"create failed: {resp}")
    print(f"instance {instance_id} created; waiting for it to come up...")

    pub = os.path.expanduser(os.environ.get("VAST_SSH_PUBKEY", "~/.ssh/id_ed25519.pub"))
    with open(pub) as f:
        client.attach_ssh(instance_id, f.read().strip())

    try:
        state = wait_ready(client, instance_id)
    except RuntimeError as e:
        sys.exit(f"{e}\ninstance {instance_id} may still be loading — check "
                 f"`python vast_train.py status --id {instance_id}`, or destroy "
                 f"with `python vast_train.py destroy --id {instance_id}`")
    state["label"] = args.label
    save_state(state)
    print(f"ssh ready: root@{state['ssh_host']} -p {state['ssh_port']} "
          f"({state.get('gpu')}, ~${(state.get('dph') or 0):.3f}/hr)")

    print("bootstrapping python deps (datasets, matplotlib)...")
    run_remote(state, "pip install -q --break-system-packages datasets matplotlib")
    print("instance ready — next: `python vast_train.py push`")


def cmd_push(args):
    state = load_state()
    run_remote(state, f"mkdir -p {REMOTE_ROOT}")
    rsync(state, "./", f"root@{state['ssh_host']}:{REMOTE_ROOT}/")
    print(f"pushed repo -> {REMOTE_ROOT}")


def cmd_ssh(args):
    state = load_state()
    if not args.cmd:
        print(" ".join(ssh_prefix(state)))
        return
    sys.exit(run_remote(state, " ".join(args.cmd), check=False).returncode)


def cmd_prepare(args):
    state = load_state()
    if not args.force:
        rc = run_remote(state, f"test -f {REMOTE_ROOT}/{DATA_DIR}/train.bin", check=False).returncode
        if rc == 0:
            print("train.bin already exists on the instance (pass --force to rebuild)")
            return
    cmd = (f"cd {REMOTE_ROOT} && {hf_env()}python -u prepare.py --output-dir {DATA_DIR} "
           f"--vocab-size {args.vocab_size} --bpe-train-docs {args.bpe_train_docs} "
           f"--holdout-period {args.holdout_period}")
    if args.max_train_docs > 0:
        cmd += f" --max-train-docs {args.max_train_docs}"
    run_remote(state, cmd)


def cmd_train(args):
    state = load_state()
    cmd = (f"cd {REMOTE_ROOT} && MPLBACKEND=Agg {hf_env()}python -u train.py "
           f"-data_dir {DATA_DIR} -dir_name {args.dir_name} "
           f"-d_model {args.d_model} -n_layers {args.n_layers} -heads {args.heads} "
           f"-kv_heads {args.kv_heads} -loops {args.loops} "
           f"-batchsize {args.batchsize} -grad_accum {args.grad_accum} "
           f"-seqlen {args.seqlen} -epochs {args.epochs} "
           f"-lr {args.lr} -muon_lr {args.muon_lr} -warmup_steps {args.warmup_steps} "
           f"-save_every {args.save_every} -val_every {args.val_every} "
           f"-early_stop {args.early_stop} -early_stop_delta {args.early_stop_delta} "
           f"-early_stop_cooldown {args.early_stop_cooldown} "
           f"-printevery {args.printevery}")
    if args.loadname:
        cmd += f" -loadname {args.loadname}"
    if args.detach:
        run_remote(state, f"nohup {cmd} > train_{args.dir_name}.log 2>&1 & echo detached pid $!")
        print(f"detached; watch with `python vast_train.py ssh tail -f train_{args.dir_name}.log`")
    else:
        run_remote(state, cmd)


